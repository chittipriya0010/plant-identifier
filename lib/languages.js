export function getDoctorFloraGreeting(plantName, language = 'en') {
  const name = plantName || 'this specimen';
  switch (language) {
    case 'hi':
      return `नमस्ते! मैं डॉ. फ्लोरा हूँ। मैंने देखा कि आपने ${name} स्कैन किया है। क्या आप इसके औषधीय उपयोग, देखभाल या विषाक्तता के बारे में कुछ पूछना चाहते हैं?`;
    case 'ur':
      return `السلام علیکم! میں ڈاکٹر فلورا ہوں۔ میں دیکھ رہی ہوں کہ آپ نے ${name} اسکین کیا ہے۔ کیا آپ اس کے طبی استعمال، نگہداشت یا زہریلے پن کے بارے میں کوئی سوال پوچھنا چاہتے ہیں؟`;
    case 'th':
      return `สวัสดีค่ะ! ฉันคือ ดร. ฟลอร่า ฉันเห็นว่าคุณได้สแกน ${name} คุณมีคำถามเกี่ยวกับสรรพคุณทางยา การดูแล หรือความเป็นพิษหรือไม่คะ?`;
    case 'ms':
      return `Halo! Saya Dr. Flora. Saya melihat anda telah mengimbas ${name}. Adakah anda mempunyai sebarang soalan tentang kegunaan perubatan, penjagaan atau ketoksikannya?`;
    case 'tl':
      return `Kumusta! Ako si Dr. Flora. Nakita kong na-scan mo ang ${name}. May mga katanungan ka ba tungkol sa mga gamit nito sa medisina, pag-aalaga, o pagiging lason?`;
    case 'ko':
      return `안녕하세요! 저는 식물 박사 닥터 플로라입니다. ${name}을(를) 스캔하셨네요. 약효, 식물 관리법 또는 반려동물 독성에 대해 궁금한 점이 있으신가요?`;
    case 'ja':
      return `こんにちは！植物専門家のフローラ博士です。${name} をスキャンしましたね。薬効、育て方、または毒性について何か質問はありますか？`;
    case 'es':
      return `¡Hola! Soy la Dra. Flora. Veo que has escaneado ${name}. ¿Tienes alguna pregunta sobre sus usos medicinales, cuidados o toxicidad?`;
    case 'fr':
      return `Bonjour ! Je suis le Dr. Flora. Je vois que vous avez scanné ${name}. Avez-vous des questions sur ses vertus médicinales, son entretien ou sa toxicité ?`;
    case 'de':
      return `Hallo! Ich bin Dr. Flora. Ich sehe, Sie haben ${name} gescannt. Haben Sie Fragen zu medizinischen Wirkungen, Pflege oder Giftigkeit?`;
    case 'ar':
      return `مرحباً! أنا د. فلورا. أرى أنك قمت بمسح ${name}. هل لديك أي أسئلة حول استخداماته الطبية أو العناية به أو سميته؟`;
    case 'ru':
      return `Здравствуйте! Я доктор Флора. Вы отсканировали ${name}. Есть ли у вас вопросы о его лечебных свойствах, уходе или токсичности?`;
    default:
      return `Hello! I'm Dr. Flora. I see you've scanned ${name}. Do you have any questions about its medicinal uses, care, or pet toxicity?`;
  }
}

export function getLanguageName(code) {
  const lang = SUPPORTED_LANGUAGES.find((l) => l.code === code);
  return lang ? lang.name : 'English';
}
